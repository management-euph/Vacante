        $pk_s['country'],
        $pk_s['city'],
        $pk_s['dep_city'],
        $pk_s['check_in'],
        $pk_total,
        $pk_matched,
        $pk_with_product,
        $pk_total > 0 ? ($pk_transport_seen ? '; transport legs in the offers' : '; NO transport service in the offers') : '',
    );
}
