/**
 * One live call. Prints the request details (never the envelope: it holds
 * the account) and how long it took.
 *
 * @return array{0: ?\SimpleXMLElement, 1: string} the response details, or null and why
 */
function pk_call(string $requestType, string $detailsXml): array
{
    global $pk_http, $pk_builder;
    echo "Request details:\n", $detailsXml, "\n";
    $started = microtime(true);
    try {
        $raw = $pk_http->post($pk_builder->envelope($requestType, $detailsXml, '901', date('Y-m-d\TH:i:s')));
    } catch (\Throwable $e) {
        echo sprintf("FAILED after %.1f s: %s\n", microtime(true) - $started, $e->getMessage());

        return [null, $e->getMessage()];
    }
    [$details, $why] = pk_details($raw);
    echo sprintf("Answered in %.1f s, %d bytes%s\n", microtime(true) - $started, strlen($raw), $why !== '' ? ' — ' . $why : '');

    return [$details, $why];
}

