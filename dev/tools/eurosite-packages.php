/**
 * eurosite-packages.php — what Eurosite's package module (Pachete) offers
 * this store, read-only: the routes, a sample search, and whether the
 * package hotels are the hotels the store already sells.
 *
 * WHY: the store sells Eurosite hotels (accommodation only); the API's
 * package module (spec "Pachete", p. 46–82) is not built yet. Before
 * designing it — board 16.2 puts "Cu autocarul / Cu avionul" on the hotel's
 * own page — two facts decide the shape: which destinations and departure
 * cities exist, and whether a package's hotel (tour operator + product
 * code) is a hotel the store has synced, with a product page to put the
 * package on.
 *
 *   1. getPackageNVRoutesRequest, per transport (bus, plane): countries,
 *      destinations (city, zone), departure cities and their dates, with
 *      how many of the store's hotels each destination city has.
 *   2. getPackageNVPriceRequest for a sample route (picked automatically,
 *      or the one you give): each hotel with its offers — availability,
 *      period, net / gross / struck price, PackageId + PackageVariantId (the
 *      booking keys), room, meal and the services (the bus or the flights
 *      with their times and seats, transfers, airport tax, package fee) —
 *      and whether the hotel is in the store's hotel list, with a product.
 *   3. A summary: how many package hotels the store already has.
 *
 * Read-only: nothing is booked, written or cached; the store's own API
 * client and its circuit breaker are not touched (this page uses its own,
 * one try a call). Only the request details are printed, never the
 * envelope with the account.
 *
 * WHERE: the fullstore sandbox only — docker/fullstore/docker-compose.yml
 * bind-mounts dev/ at /var/www/html/dev. Refuses non-localhost HTTP requests.
 *
 * USE:
 *   http://localhost:8080/dev/tools/eurosite-packages.php
 *       → bus and plane routes, then one sample search per transport
 *   ...?transport=bus                      → bus only (bus, plane or search = all)
 *   ...?sample=3                           → search 3 destinations per transport
 *   ...?city=BGNIS&dep_city=ROBCH1&check_in=2027-07-03&nights=7
 *       [&country=BG&dep_country=RO&transport=bus&zone=BGVAR&tourop=LA]
 *                                          → this search instead of the automatic one
 *   ...&adults=2&children=8,5&room=DB      → the room searched (default DB, 2 adults)
 *   ...&search=0                           → routes only
 *   ...&raw=1                              → also the raw XML of the routes and of the first hotel
 *   ...&lines=200                          → route lines printed per transport (default 80)
 *   CLI: docker compose exec app php /var/www/html/dev/tools/eurosite-packages.php transport=bus sample=2
 *        (or php /repo/dev/tools/eurosite-packages.php … on an older container)
 */

