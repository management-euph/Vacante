                        "  %s: %s %s%s\n",
                        $pk_pr['name'] !== '' ? $pk_pr['name'] : 'code ' . $pk_pr['code'],
                        $pk_pr['price'],
                        $pk_pr['currency'] !== '' ? $pk_pr['currency'] : 'EUR',
                        $pk_pr['gross'] !== '' && $pk_pr['gross'] !== $pk_pr['price'] ? ' (recommended ' . $pk_pr['gross'] . ')' : '',
                    );
                }
            }
            $pk_supp[] = $pk_row;
        }
    }
