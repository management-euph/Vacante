/**
 * The charter route to search: from Romania, Bucharest first, to the arrival
 * cities with the most store hotels (abroad first, then by name), never to
 * the departure city itself.
 *
 * @param list<array{country_code: string, country_name: string, city_code: string, city_name: string}> $departures pk_charter_cities() of the departures
 * @param list<array{country_code: string, country_name: string, city_code: string, city_name: string}> $arrivals pk_charter_cities() of the arrivals
 * @param array<string, int> $storeHotels city code => store hotels
 * @param int $count how many destinations
 *
 * @return array{from: ?array{country_code: string, country_name: string, city_code: string, city_name: string}, to: list<array{country_code: string, country_name: string, city_code: string, city_name: string}>}
 */
function pk_charter_pick(array $departures, array $arrivals, array $storeHotels, int $count): array
{
    $from = null;
    $best = -1;
    foreach ($departures as $city) {
        $score = ($city['country_code'] === 'RO' ? 2 : 0) + (preg_match('/^ROB|bucur|buchar/i', $city['city_code'] . ' ' . $city['city_name']) === 1 ? 1 : 0);
        if ($score > $best) {
            [$best, $from] = [$score, $city];
        }
    }
    $home = $from['country_code'] ?? '';
    $to = array_values(array_filter($arrivals, static fn (array $c): bool => $from === null || $c['city_code'] !== $from['city_code']));
    usort($to, static fn (array $a, array $b): int => [$storeHotels[$b['city_code']] ?? 0, $a['country_code'] === $home ? 1 : 0, $a['city_name']]
        <=> [$storeHotels[$a['city_code']] ?? 0, $b['country_code'] === $home ? 1 : 0, $b['city_name']]);

    return ['from' => $from, 'to' => array_slice($to, 0, max(0, $count))];
}

/**
 * The departure dates to try for a charter: the one given; else a fortnight
 * and six weeks ahead, then next summer's 1 July and 1 August (charters run
 * by season). FlexibleDate catches the days around each.
 *
 * @return list<string>
 */
function pk_charter_dates(string $today, string $given = ''): array
{
    if ($given !== '') {
        return [$given];
    }
    $dates = [date('Y-m-d', (int) strtotime($today . ' +14 days')), date('Y-m-d', (int) strtotime($today . ' +45 days'))];
    $soonest = date('Y-m-d', (int) strtotime($today . ' +2 days'));
    $year = (int) substr($today, 0, 4);
    foreach (['07-01', '08-01'] as $monthDay) {
        $date = $year . '-' . $monthDay;
        $dates[] = $date >= $soonest ? $date : ($year + 1) . '-' . $monthDay;
    }
    $dates = array_values(array_unique($dates));
    sort($dates);

    return $dates;
}

/**
 * The persons of a charter or supplement request: "ADULT 1"…, then the
 * children with their age.
 *
 * @param list<int> $childAges
 */
function pk_pax_xml(int $adults, array $childAges): string
{
    $xml = '';
    for ($i = 1; $i <= max(1, $adults); $i++) {
        $xml .= '<PaxName PaxType="adult">ADULT ' . $i . '</PaxName>';
    }
    foreach (array_values($childAges) as $i => $age) {
        $xml .= '<PaxName PaxType="child" ChildAge="' . (int) $age . '">COPIL ' . ($i + 1) . '</PaxName>';
    }

    return '<PaxNames>' . $xml . '</PaxNames>';
}

/**
 * The offer to ask supplements for, in a city's hotel search answer: the
 * first store hotel with an immediate offer, else with any offer.
 *
 * @param list<array{product: array<string, string>, offers: list<array<string, mixed>>}> $hotels pk_offers() of a getHotelPriceResponse
 * @param array<string, mixed> $storeKeys "TOUROP|CODE" => the store's row, for the hotels that may be picked
 *
 * @return ?array{hotel: array{product: array<string, string>, offers: list<array<string, mixed>>}, offer: array<string, mixed>}
 */
function pk_supplement_offer(array $hotels, array $storeKeys): ?array
{
    $fallback = null;
    foreach ($hotels as $hotel) {
        if (!array_key_exists($hotel['product']['tourop'] . '|' . $hotel['product']['code'], $storeKeys)) {
            continue;
        }
        foreach ($hotel['offers'] as $offer) {
            if (($offer['variant_id'] ?? '') === '') {
                continue;
            }
            if (($offer['availability'] ?? '') === 'IM') {
                return ['hotel' => $hotel, 'offer' => $offer];
            }
            $fallback ??= ['hotel' => $hotel, 'offer' => $offer];
        }
    }

    return $fallback;
}

/**
 * The stays to ask a hotel's supplements for: the one given; else a month
 * ahead, and next summer's 1 July when it is well apart and its offers can
 * be loaded already (transport supplements are often the season's).
 *
 * @return list<string> empty when the date given is not YYYY-MM-DD
 */
function pk_supplement_dates(string $today, string $given = ''): array
{
    if ($given !== '') {
        return preg_match('/^\d{4}-\d{2}-\d{2}$/', $given) === 1 ? [$given] : [];
    }
    $near = date('Y-m-d', (int) strtotime($today . ' +30 days'));
    $apart = date('Y-m-d', (int) strtotime($near . ' +42 days'));
    $latest = date('Y-m-d', (int) strtotime($today . ' +300 days'));
    $year = (int) substr($today, 0, 4);
    foreach ([$year . '-07-01', ($year + 1) . '-07-01'] as $summer) {
        if ($summer >= $apart && $summer <= $latest) {
            return [$near, $summer];
        }
    }

    return [$near];
}

/** "2026-12-19 15:40 → 17:35" from two API times (seconds dropped, the date once when it is the same). */
function pk_span(string $from, string $to): string
{
    $trim = static fn (string $t): string => preg_replace('/^(\d{4}-\d{2}-\d{2} \d{2}:\d{2}):00$/', '$1', trim($t)) ?? trim($t);
    [$from, $to] = [$trim($from), $trim($to)];
    if ($to === '' || $to === $from) {
        return $from;
    }
    if (strlen($from) > 10 && strlen($to) > 10 && substr($from, 0, 10) === substr($to, 0, 10)) {
        return $from . ' → ' . substr($to, 11);
    }

    return $from . ' → ' . $to;
}

/**
 * What an error message must not show (the repo is public and these pages
 * get pasted): the API address, its host, the account — longest first.
 *
 * @param array<string, mixed> $settings ConfigProvider::toClientSettings()
 *
 * @return list<string>
 */
function pk_secrets(array $settings): array
{
    $url = is_string($settings['api_url'] ?? null) ? $settings['api_url'] : '';
    $host = parse_url($url, PHP_URL_HOST);
    $secrets = array_values(array_unique(array_filter([
        $url,
        is_string($host) ? $host : '',
        is_string($settings['api_user'] ?? null) ? $settings['api_user'] : '',
        is_string($settings['api_password'] ?? null) ? $settings['api_password'] : '',
    ], static fn (string $s): bool => strlen(trim($s)) >= 3)));
    usort($secrets, static fn (string $a, string $b): int => strlen($b) <=> strlen($a));

    return $secrets;
}

/**
 * @param list<string> $secrets pk_secrets()
 */
function pk_mask(string $text, array $secrets): string
{
    foreach ($secrets as $secret) {
        $text = str_ireplace($secret, '<hidden>', $text);
    }

    return $text;
}

