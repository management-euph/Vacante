/**
 * The legs of a getCharterPriceResponse: each <Charter> — Departure (the way
 * out) or Return (the way back) — with its places and offers (spec p. 86–88).
 *
 * @return list<array{type: string, from: array{country: string, city: string, name: string}, to: array{country: string, city: string, name: string}, offers: list<array<string, string>>}>
 */
function pk_charters(\SimpleXMLElement $response): array
{
    $place = static fn (?\SimpleXMLElement $p): array => [
        'country' => pk_text($p?->CountryCode),
        'city' => pk_text($p?->CityCode),
        'name' => pk_text($p?->CityName),
    ];
    $out = [];
    foreach ($response->Charter ?? [] as $charter) {
        $offers = [];
        foreach ($charter->Offers->Offer ?? [] as $o) {
            $offers[] = [
                'tourop' => pk_text($o->TourOpCode),
                'availability' => (string) ($o->Availability['Code'] ?? ''),
                'charter_nr' => pk_text($o->CharterNr),
                'charter_id' => pk_text($o->CharterId),
                'transport' => pk_text($o->Transport),
                'departure_id' => pk_text($o->DepartureId),
                'departure' => pk_text($o->Departure),
                'arrival' => pk_text($o->Arrival),
                'seats' => pk_text($o->Disponibility),
                'flight' => pk_text($o->FlightNumber),
                'price' => pk_text($o->ProductPrice),
                'currency' => (string) ($o['CurrencyCode'] ?? ''),
            ];
        }
        $out[] = [
            'type' => (string) ($charter['Type'] ?? ''),
            'from' => $place($charter->Departure),
            'to' => $place($charter->Destination),
            'offers' => $offers,
        ];
    }

    return $out;
}

