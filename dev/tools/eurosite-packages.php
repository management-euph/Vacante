/** The <ResponseDetails> child of an answer, or the reason there is none. */
function pk_details(string $raw): array
{
    $doc = @simplexml_load_string($raw, \SimpleXMLElement::class, LIBXML_NONET | LIBXML_NOCDATA);
    if (!$doc instanceof \SimpleXMLElement) {
        return [null, 'the answer is not XML (' . strlen($raw) . ' bytes)'];
    }
    $details = $doc->ResponseDetails;
    foreach (($details instanceof \SimpleXMLElement ? $details->children() : null) ?? [] as $child) {
        if ($child->getName() === 'Errors') {
            return [null, 'API error: ' . trim(preg_replace('/\s+/', ' ', strip_tags(str_replace('><', '> <', (string) $child->asXML()))) ?? '')];
        }

        return [$child, ''];
    }

    return [null, 'no <ResponseDetails> in the answer'];
}

function pk_text(?\SimpleXMLElement $el): string
{
    return $el === null ? '' : trim(preg_replace('/\s+/u', ' ', (string) $el) ?? '');
}

/**
 * The routes of a getPackageNVRoutesResponse.
 *
 * @return list<array{country_code: string, country_name: string, city_code: string, city_name: string, zone_code: string, zone_name: string, departures: list<array{country_code: string, country_name: string, city_code: string, city_name: string, dates: list<string>}>}>
 */
function pk_routes(\SimpleXMLElement $response): array
{
    $out = [];
    foreach ($response->Country ?? [] as $country) {
        foreach ($country->Destinations->Destination ?? [] as $dest) {
            $departures = [];
            foreach ($dest->Departures->Departure ?? [] as $dep) {
                $dates = [];
                foreach ($dep->Dates->Date ?? [] as $date) {
                    $d = pk_text($date);
                    if ($d !== '') {
                        $dates[] = $d;
                    }
                }
                sort($dates);
                $departures[] = [
                    'country_code' => pk_text($dep->CountryCode),
                    'country_name' => pk_text($dep->CountryName),
                    'city_code' => pk_text($dep->CityCode),
                    'city_name' => pk_text($dep->CityName),
                    'dates' => array_values(array_unique($dates)),
                ];
            }
            $out[] = [
                'country_code' => pk_text($country->CountryCode),
                'country_name' => pk_text($country->CountryName),
                'city_code' => pk_text($dest->CityCode),
                'city_name' => pk_text($dest->CityName),
                'zone_code' => pk_text($dest->ZoneCode),
                'zone_name' => pk_text($dest->ZoneName),
                'departures' => $departures,
            ];
        }
    }

    return $out;
}

/** What a service type of a package offer is (spec p. 50–61). */
function pk_service_kind(string $type): string
{
    return match (strtolower($type)) {
        '2' => 'meal',
        '6' => 'other service',
        '7' => 'transport',
        '7s' => 'transport extra (tax…)',
        '8' => 'package fee',
        default => 'type ' . $type,
    };
}

/**
 * The hotels and offers of a getPackageNVPriceResponse.
 *
 * @return list<array{product: array<string, string>, offers: list<array<string, mixed>>}>
 */
function pk_offers(\SimpleXMLElement $response): array
{
    $out = [];
    foreach ($response->Hotel ?? [] as $hotel) {
        $p = $hotel->Product;
        $product = [
            'tourop' => pk_text($p->TourOpCode),
            'code' => pk_text($p->ProductCode),
            'name' => pk_text($p->ProductName),
            'country' => pk_text($p->CountryCode),
            'city_code' => pk_text($p->CityCode),
            'city_name' => pk_text($p->CityName),
            'category' => pk_text($p->ProductCategory),
            'class' => pk_text($p->Class),
        ];
        $offers = [];
        foreach ($hotel->Offers->Offer ?? [] as $o) {
            $rooms = [];
            foreach ($o->BookingRoomTypes->Room ?? [] as $r) {
                $rooms[] = ['code' => (string) $r['Code'], 'gcode' => (string) $r['GCode'], 'quantity' => (string) $r['Quantity'], 'price' => (string) $r['ServicePrice'], 'name' => pk_text($r)];
            }
            $meals = [];
            foreach ($o->Meals->Meal ?? [] as $m) {
                $meals[] = ['type' => (string) $m['Type'], 'code' => (string) $m['Code'], 'price' => (string) $m['ServicePrice'], 'name' => pk_text($m)];
            }
            $services = [];
            foreach ($o->PriceDetails->Services->Service ?? [] as $s) {
                $services[] = [
                    'type' => pk_text($s->Type),
                    'kind' => pk_service_kind(pk_text($s->Type)),
                    'code' => pk_text($s->Code),
                    'name' => pk_text($s->Name),
                    'transport' => pk_text($s->Transport),
                    'availability' => (string) ($s->Availability['Code'] ?? ''),
                    'from' => pk_text($s->PeriodOfStay->CheckIn),
                    'to' => pk_text($s->PeriodOfStay->CheckOut),
                    'seats' => pk_text($s->Seats),
                    'price' => pk_text($s->ServicePrice),
                ];
            }
            $offers[] = [
                'type' => pk_text($o->OfferType),
                'availability' => (string) ($o->Availability['Code'] ?? ''),
                'check_in' => pk_text($o->PeriodOfStay->CheckIn),
                'check_out' => pk_text($o->PeriodOfStay->CheckOut),
                'currency' => (string) ($o['CurrencyCode'] ?? ''),
                'price' => pk_text($o->ProductPrice),
                'gross' => pk_text($o->Gross),
                'no_redd' => pk_text($o->PriceNoRedd),
                'description' => pk_text($o->OfferDescription),
                'grila' => pk_text($o->GrilaName),
                'package_id' => pk_text($o->PackageId),
                'variant_id' => pk_text($o->PackageVariantId),
                'rooms' => $rooms,
                'meals' => $meals,
                'services' => $services,
            ];
        }
        $out[] = ['product' => $product, 'offers' => $offers];
    }

    return $out;
}

/**
 * The departure date to search from a route: the first one at least $minDays
 * after $today.
 *
 * @param list<string> $dates
 */
function pk_next_date(array $dates, string $today, int $minDays = 2): string
{
    $from = date('Y-m-d', (int) strtotime($today . ' +' . $minDays . ' days'));
    foreach ($dates as $date) {
        if (substr($date, 0, 10) >= $from) {
            return substr($date, 0, 10);
        }
    }

    return '';
}

/**
 * The sample routes to search: the destinations with the most store
 * hotels first (then the most dates), each from a departure in Romania,
 * Bucharest first, on its next date.
 *
 * @param list<array<string, mixed>> $routes pk_routes()
 * @param array<string, int> $storeHotels city code => store hotels
 *
 * @return list<array{country: string, city: string, city_name: string, zone: string, dep_country: string, dep_city: string, dep_name: string, check_in: string}>
 */
function pk_pick(array $routes, array $storeHotels, string $today, int $count): array
{
    $candidates = [];
    foreach ($routes as $route) {
        $best = null;
        foreach ($route['departures'] as $dep) {
            $date = pk_next_date($dep['dates'], $today);
            if ($date === '') {
                continue;
            }
            $score = ($dep['country_code'] === 'RO' ? 2 : 0) + (preg_match('/^ROB|bucur/i', $dep['city_code'] . ' ' . $dep['city_name']) === 1 ? 1 : 0);
            if ($best === null || $score > $best[0] || ($score === $best[0] && $date < $best[1]['check_in'])) {
                $best = [$score, ['dep_country' => $dep['country_code'], 'dep_city' => $dep['city_code'], 'dep_name' => $dep['city_name'], 'check_in' => $date, 'dates' => count($dep['dates'])]];
            }
        }
        if ($best === null) {
            continue;
        }
        $candidates[] = [
            'hotels' => $storeHotels[$route['city_code']] ?? 0,
            'dates' => $best[1]['dates'],
            'pick' => [
                'country' => $route['country_code'],
                'city' => $route['city_code'],
                'city_name' => $route['city_name'],
                'zone' => $route['zone_code'],
                'dep_country' => $best[1]['dep_country'],
                'dep_city' => $best[1]['dep_city'],
                'dep_name' => $best[1]['dep_name'],
                'check_in' => $best[1]['check_in'],
            ],
        ];
    }
    usort($candidates, static fn (array $a, array $b): int => [$b['hotels'], $b['dates'], $a['pick']['city']] <=> [$a['hotels'], $a['dates'], $b['pick']['city']]);

    return array_slice(array_column($candidates, 'pick'), 0, max(0, $count));
}

