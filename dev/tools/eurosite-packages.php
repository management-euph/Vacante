/**
 * eurosite-packages.php — how this store's Eurosite account can sell
 * transport with a hotel, read-only: the package module (Pachete), the
 * charters (Transport) and a hotel's own transport supplement.
 *
 * WHY: the store sells Eurosite hotels (accommodation only); the API's
 * package module (spec "Pachete", p. 46–82) is not built yet. Before
 * designing it — board 16.2 puts "Cu autocarul / Cu avionul" on the hotel's
 * own page — a few facts decide the shape: which destinations and departure
 * cities exist, whether a package's hotel (tour operator + product code) is
 * a hotel the store has synced, with a product page to put the package on,
 * and, when the account gets no package, whether the transport comes
 * another way: as a charter of its own (spec "Transport", p. 84–), or as a
 * supplement of the hotel offer (getHotelServiceTypesRequest Type 7).
 *
 *   1. getPackageNVRoutesRequest with Transport=search — every package, which
 *      the spec says is in general enough (bus or plane only on request): countries,
 *      destinations (city, zone), departure cities and their dates, with
 *      how many of the store's hotels each destination city has.
 *   2. getPackageNVPriceRequest for a sample route (picked automatically,
 *      or the one you give): each hotel with its offers — availability,
 *      period, net / gross / struck price, PackageId + PackageVariantId (the
 *      booking keys), room, meal and the services (the bus or the flights
 *      with their times and seats, transfers, airport tax, package fee) —
 *      and whether the hotel is in the store's hotel list, with a product.
 *   3. getCharterCitiesRequest, departures then arrivals: the charter cities,
 *      with the store's hotels in each arrival city.
 *   4. getCharterPriceRequest for a sample route (from Bucharest to the
 *      arrival city with the most store hotels, or the one you give), on a
 *      few dates until one answers: the way out and back, each flight or bus
 *      with its times, seats, price and CharterId.
 *   5. A store hotel's supplements: getHotelPriceRequest for its city (the
 *      storefront's own search), then getHotelServiceTypesRequest on its
 *      offer — meals (Type 2), other services (6), transport (7, with a
 *      CharterId when it is a charter) — and the price of each transport
 *      supplement (getHotelServicePriceRequest). Also what the offer itself
 *      already includes (resort tax and the like).
 *   6. A summary: which of the three ways this account has.
 *
 * Read-only: nothing is booked, written or cached; the store's own API
 * client and its circuit breaker are not touched (this page uses its own,
 * one try a call). Only the request details are printed, never the
 * envelope with the account.
 *
 * WHERE: the fullstore sandbox only — docker/fullstore/docker-compose.yml
 * bind-mounts dev/ at /var/www/html/dev. Refuses non-localhost HTTP requests.
 *
 * USE:
 *   http://localhost:8080/dev/tools/eurosite-packages.php
 *       → every package's routes (Transport=search), a sample package search,
 *         the charters, and the supplements of 3 store hotels
 *   ...?transport=bus,plane                → bus and plane apart instead (bus, plane, search)
 *   ...?sample=3                           → search 3 destinations (per transport asked)
 *   ...?city=BGNIS&dep_city=ROBCH1&check_in=2027-07-03&nights=7
 *       [&country=BG&dep_country=RO&transport=search&zone=BGVAR&tourop=LA]
 *                                          → this package search instead of the automatic one
 *   ...&adults=2&children=8,5&room=DB      → the persons and room asked (default DB, 2 adults)
 *   ...&search=0                           → package routes, no package search
 *   ...&packages=0 / &charter=0 / &supplements=0
 *                                          → leave out steps 1–2 / 3–4 / 5
 *   ...&charter_from=ROBCH1&charter_to=GRHRK&charter_date=2027-07-03&nights=7
 *                                          → this charter route / date (FlexibleDate) instead
 *   ...&charter_sample=3                   → search 3 charter destinations
 *   ...&supplements=5                      → ask 5 store hotels (one per city, busiest cities first)
 *   ...&hotel=ALTUS (product code or part of the name) or &hotel_city=RO0218
 *       [&hotel_check_in=2027-07-10&hotel_nights=7]
 *                                          → that hotel / that city's hotel, on these dates
 *   ...&raw=1                              → also the raw XML of the answers
 *   ...&lines=200                          → route lines printed per transport (default 80)
 *   CLI: docker compose exec app php /var/www/html/dev/tools/eurosite-packages.php sample=2
 *        (or php /repo/dev/tools/eurosite-packages.php … on an older container)
 */

