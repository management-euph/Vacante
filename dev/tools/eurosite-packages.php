            . '<DepCountryCode>' . $pk_builder::esc($pk_s['dep_country']) . '</DepCountryCode>'
            . '<DepCityCode>' . $pk_builder::esc($pk_s['dep_city']) . '</DepCityCode>'
            . '<Transport>' . $pk_builder::esc($pk_s['transport']) . '</Transport>'
            . (pk_param('tourop') !== '' ? '<TourOpCode>' . $pk_builder::esc(strtoupper(pk_param('tourop'))) . '</TourOpCode>' : '')
            . '<CurrencyCode>EUR</CurrencyCode>'
            . '<Language>RO</Language>'
            . '<OfferType>TOATE</OfferType>'
            . '<PeriodOfStay><CheckIn>' . $pk_builder::esc($pk_s['check_in']) . '</CheckIn><CheckOut>' . $pk_out . '</CheckOut></PeriodOfStay>'
            . '<Days>1</Days>'
            . '<Rooms>' . $pk_builder->roomElement($pk_room) . '</Rooms>'
            . '</getPackageNVPriceRequest>');
        if ($pk_resp === null) {
            continue;
        }
        $pk_hotels = pk_offers($pk_resp);
        echo count($pk_hotels), " hotel(s) answered\n";
        if ($pk_hotels !== []) {
            if ($pk_raw) {
                echo "\nRaw first <Hotel>:\n", pk_xml($pk_resp->Hotel[0]), "\n";
            }
            break;
        }
    }
    if ($pk_hotels === []) {
        echo "\nNo package hotel for this route on these dates.\n";
        $pk_summary[] = [$pk_s, 0, 0, 0, false];
        continue;
    }

    // The store's own copy of each package hotel.
    $pk_keys = array_map(static fn (array $h): string => $h['product']['tourop'] . '|' . $h['product']['code'], $pk_hotels);
    $pk_store_rows = [];
    foreach (db_get_array(
        "SELECT h.tourop_code, h.product_code, h.name, h.city_code, h.product_id, h.sync_status, pd.product AS product_name"
        . ' FROM ?:eurosite_hotels h'
        . ' LEFT JOIN ?:product_descriptions pd ON pd.product_id = h.product_id AND pd.lang_code = ?s'
        . " WHERE CONCAT(h.tourop_code, '|', h.product_code) IN (?a)",
        defined('CART_LANGUAGE') ? CART_LANGUAGE : 'ro',
        $pk_keys,
    ) as $pk_r) {
        $pk_store_rows[$pk_r['tourop_code'] . '|' . $pk_r['product_code']] = $pk_r;
    }

    $pk_matched = 0;
    $pk_with_product = 0;
    $pk_transport_seen = false;
    $pk_max_hotels = max(1, (int) pk_param('hotels', '20'));
    $pk_max_offers = max(1, (int) pk_param('offers', '3'));
    foreach ($pk_hotels as $pk_hi => $pk_h) {
        $pk_p = $pk_h['product'];
        $pk_store = $pk_store_rows[$pk_p['tourop'] . '|' . $pk_p['code']] ?? null;
        if ($pk_store !== null) {
            $pk_matched++;
            if ((int) $pk_store['product_id'] > 0) {
                $pk_with_product++;
            }
        }
        foreach ($pk_h['offers'] as $pk_o) {
            foreach ($pk_o['services'] as $pk_sv) {
                $pk_transport_seen = $pk_transport_seen || $pk_sv['type'] === '7';
            }
        }
        if ($pk_hi >= $pk_max_hotels) {
            continue;
        }
        echo sprintf(
            "\n%s %s (%s) · %s★ %s · %s %s · store: %s\n",
            $pk_p['tourop'],
            $pk_p['code'],
            $pk_p['name'],
            $pk_p['category'],
            $pk_p['class'],
            $pk_p['city_name'],
            $pk_p['city_code'],
            $pk_store === null
                ? 'NOT in the store\'s hotel list'
                : ((int) $pk_store['product_id'] > 0
                    ? 'product #' . $pk_store['product_id'] . ' "' . ($pk_store['product_name'] ?: $pk_store['name']) . '"'
                    : 'in the hotel list (' . $pk_store['sync_status'] . '), no product yet'),
        );
        foreach (array_slice($pk_h['offers'], 0, $pk_max_offers) as $pk_o) {
            $pk_r0 = $pk_o['rooms'][0] ?? null;
            $pk_m0 = $pk_o['meals'][0] ?? null;
            echo sprintf(
                "  • %s %s · %s → %s · net %s %s, gross %s%s · PackageId %s · VariantId %s\n    room %s%s · meal %s%s%s\n",
                $pk_o['type'],
                $pk_o['availability'],
                $pk_o['check_in'],
                $pk_o['check_out'],
                $pk_o['price'],
                $pk_o['currency'],
                $pk_o['gross'],
                $pk_o['no_redd'] !== '' && $pk_o['no_redd'] !== $pk_o['gross'] ? ', without reduction ' . $pk_o['no_redd'] : '',
                $pk_o['package_id'] !== '' ? $pk_o['package_id'] : '—',
                $pk_o['variant_id'] !== '' ? $pk_o['variant_id'] : '—',
                $pk_r0 !== null ? $pk_r0['gcode'] . ' "' . $pk_r0['name'] . '" (code ' . $pk_r0['code'] . ')' : '—',
                count($pk_o['rooms']) > 1 ? ' +' . (count($pk_o['rooms']) - 1) : '',
                $pk_m0 !== null ? $pk_m0['name'] . ' (type ' . $pk_m0['type'] . ')' : '—',
                $pk_o['grila'] !== '' ? ' · grid ' . $pk_o['grila'] : '',
                $pk_o['description'] !== '' ? "\n    offer: " . $pk_o['description'] : '',
            );
            foreach ($pk_o['services'] as $pk_sv) {
                echo sprintf(
                    "    - [%s %s] %s%s · %s%s%s · %s%s\n",
                    $pk_sv['type'],
                    $pk_sv['kind'],
                    $pk_sv['name'],
                    $pk_sv['transport'] !== '' ? ' (' . $pk_sv['transport'] . ')' : '',
                    $pk_sv['from'],
                    $pk_sv['to'] !== '' && $pk_sv['to'] !== $pk_sv['from'] ? ' → ' . $pk_sv['to'] : '',
                    $pk_sv['seats'] !== '' ? ' · ' . $pk_sv['seats'] . ' seats' : '',
                    $pk_sv['price'] !== '' ? $pk_sv['price'] : '—',
                    $pk_sv['availability'] !== '' ? ' · ' . $pk_sv['availability'] : '',
                );
            }
        }
        if (count($pk_h['offers']) > $pk_max_offers) {
            echo '  … ', count($pk_h['offers']) - $pk_max_offers, " more offer(s)\n";
        }
    }
    if (count($pk_hotels) > $pk_max_hotels) {
        echo "\n… ", count($pk_hotels) - $pk_max_hotels, " more hotel(s) (&hotels=100 shows them)\n";
    }
    $pk_summary[] = [$pk_s, count($pk_hotels), $pk_matched, $pk_with_product, $pk_transport_seen];
}

// ---------------------------------------------------------------- 3. summary
