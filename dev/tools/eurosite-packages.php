    if ($pk_route['from'] === null || $pk_route['to'] === []) {
        echo "No charter route to search: the answers above hold no departure or no arrival city.\n"
            . "A route you name still runs: &charter_from=ROBCH1&charter_to=GRHRK&charter_date=YYYY-MM-DD.\n";
    }
    $pk_charter_nights = max(1, (int) pk_param('nights', '7'));
    $pk_charter_offers = max(1, (int) pk_param('offers', '3'));
    foreach ($pk_route['from'] !== null ? $pk_route['to'] : [] as $pk_to) {
        $pk_from = $pk_route['from'];
        $pk_found = [0, ''];
        $pk_shown_empty = false;
        foreach (pk_charter_dates($pk_today, pk_param('charter_date')) as $pk_date) {
            $pk_back = date('Y-m-d', (int) strtotime($pk_date . ' +' . $pk_charter_nights . ' days'));
            echo sprintf(
                "\n-- %s %s (%s) → %s %s (%s): out %s, back %s\n",
                $pk_from['city_name'],
                $pk_from['city_code'],
                $pk_from['country_code'],
                $pk_to['city_name'],
                $pk_to['city_code'],
                $pk_to['country_code'],
                $pk_date,
                $pk_back,
            );
            [$pk_resp] = pk_call('getCharterPriceRequest', '<getCharterPriceRequest>'
                . '<Transport>search</Transport>'
                . '<Departure><CountryCode>' . $pk_builder::esc($pk_from['country_code']) . '</CountryCode><CityCode>' . $pk_builder::esc($pk_from['city_code']) . '</CityCode></Departure>'
                . '<Destination><CountryCode>' . $pk_builder::esc($pk_to['country_code']) . '</CountryCode><CityCode>' . $pk_builder::esc($pk_to['city_code']) . '</CityCode></Destination>'
                . '<DepartureDate>' . $pk_builder::esc($pk_date) . '</DepartureDate>'
                . '<CurrencyCode>EUR</CurrencyCode>'
                . '<ReturnDate>' . $pk_back . '</ReturnDate>'
                . '<FlexibleDate>true</FlexibleDate>'
                . '<Language>RO</Language>'
                . pk_pax_xml($pk_room['adults'], $pk_room['children'])
                . '</getCharterPriceRequest>');
            if ($pk_resp === null) {
                continue;
            }
            $pk_legs = pk_charters($pk_resp);
            $pk_n = array_sum(array_map(static fn (array $leg): int => count($leg['offers']), $pk_legs));
            echo $pk_n, ' offer(s) in ', count($pk_legs), " leg(s)\n";
            foreach ($pk_legs as $pk_leg) {
                echo sprintf(
                    "  %s: %s %s (%s) → %s %s (%s), %d offer(s)\n",
                    $pk_leg['type'] !== '' ? $pk_leg['type'] : '?',
                    $pk_leg['from']['name'],
                    $pk_leg['from']['city'],
                    $pk_leg['from']['country'],
                    $pk_leg['to']['name'],
                    $pk_leg['to']['city'],
                    $pk_leg['to']['country'],
                    count($pk_leg['offers']),
                );
                foreach (array_slice($pk_leg['offers'], 0, $pk_charter_offers) as $pk_o) {
                    echo sprintf(
                        "    • %s %s \"%s\"%s · %s · %s seat(s) · %s %s · CharterId %s · DepartureId %s · %s\n",
                        $pk_o['availability'],
                        $pk_o['transport'],
                        $pk_o['charter_nr'],
                        $pk_o['flight'] !== '' ? ' ' . $pk_o['flight'] : '',
                        pk_span($pk_o['departure'], $pk_o['arrival']),
                        $pk_o['seats'] !== '' ? $pk_o['seats'] : '?',
                        $pk_o['price'],
                        $pk_o['currency'],
                        $pk_o['charter_id'],
                        $pk_o['departure_id'],
                        $pk_o['tourop'],
                    );
                }
                if (count($pk_leg['offers']) > $pk_charter_offers) {
                    echo '    … ', count($pk_leg['offers']) - $pk_charter_offers, " more offer(s) (&offers=20 shows them)\n";
                }
            }
            if ($pk_n === 0 && !$pk_shown_empty) {
                echo "The answer holds no offer. Its content:\n", pk_xml($pk_resp, 2000), "\n";
                $pk_shown_empty = true;
            }
            if ($pk_raw && $pk_n > 0) {
                echo "\nRaw answer (start):\n", pk_xml($pk_resp, 8000), "\n";
            }
            if ($pk_n > 0) {
                $pk_found = [$pk_n, $pk_date];
                break;
            }
        }
        if ($pk_found[0] === 0) {
            echo "\nNo charter offer on these dates — try &charter_date=YYYY-MM-DD (FlexibleDate takes the days around it).\n";
        }
        $pk_charter['searched'][] = ['from' => $pk_from['city_code'], 'to' => $pk_to['city_code'], 'offers' => $pk_found[0], 'date' => $pk_found[1]];
        $pk_charter['offers'] += $pk_found[0];
    }
}

// ---------------------------------------------------------------- 5. a store hotel's supplements
$pk_supp = null; // per hotel and stay asked, for the summary
$pk_supp_count = max(0, min(20, (int) pk_param('supplements', '2')));
if ($pk_supp_count > 0) {
    $pk_supp = [];
    $pk_hdates = pk_supplement_dates($pk_today, pk_param('hotel_check_in'));
    if ($pk_hdates === []) {
        exit("hotel_check_in must be YYYY-MM-DD\n");
    }
    $pk_hn = max(1, min(21, (int) pk_param('hotel_nights', '7')));

    // Which hotels: the one named (&hotel=), else one per city — the city
    // named (&hotel_city=), or the busiest whitelisted ones (the storefront
    // searches no other).
    $pk_hotel = pk_param('hotel');
    $pk_hotel_city = strtoupper(pk_param('hotel_city'));
    $pk_named = $pk_hotel !== '' || $pk_hotel_city !== '';
    $pk_by_city = [];
    foreach (db_get_array(
        'SELECT country_code, city_code, tourop_code, product_code, name, product_id FROM ?:eurosite_hotels'
        . " WHERE sync_status = 'active' AND product_id > 0"
        . ($pk_hotel !== '' ? db_quote(' AND (product_code = ?s OR name LIKE ?l)', strtoupper($pk_hotel), '%' . $pk_hotel . '%') : '')
        . ($pk_hotel_city !== '' ? db_quote(' AND city_code = ?s', $pk_hotel_city) : '')
        . ' ORDER BY city_code, product_code',
    ) as $pk_r) {
        $pk_by_city[(string) $pk_r['city_code']][] = $pk_r;
    }
    uksort($pk_by_city, static fn (string $a, string $b): int => [count($pk_by_city[$b]), $a] <=> [count($pk_by_city[$a]), $b]);
    $pk_asked = [];
    foreach ($pk_by_city as $pk_city => $pk_list) {
        if ($pk_named || $pk_whitelist->isCityAllowed((string) $pk_list[0]['country_code'], (string) $pk_city)) {
            $pk_asked[(string) $pk_city] = $pk_list;
        }
        if (count($pk_asked) >= $pk_supp_count) {
            break;
        }
    }
    if ($pk_asked === []) {
        pk_h('5. Hotel supplements — getHotelServiceTypesRequest');
        echo $pk_named
            ? "No active store hotel with a product matches &hotel= / &hotel_city=.\n"
            : "The store has no active hotel with a product in a whitelisted city.\n";
    }

    $pk_api = Container::getApi();
    $pk_payload_of = new \ReflectionMethod(EurositeApiClient::class, 'buildHotelPricePayload');
    $pk_si = 0;
    foreach ($pk_asked as $pk_city => $pk_list) {
        $pk_si++;
        $pk_country = (string) $pk_list[0]['country_code'];
        $pk_keys = [];
        foreach ($pk_list as $pk_r) {
            $pk_keys[$pk_r['tourop_code'] . '|' . $pk_r['product_code']] = $pk_r;
        }
        // The storefront asks each tour operator of the city apart; the first hotel's is enough here.
        $pk_tourop = (string) $pk_list[0]['tourop_code'];
        pk_h(sprintf('5.%d Hotel supplements — %s %s (%d store hotel(s)), tour operator %s', $pk_si, $pk_country, $pk_city, count($pk_list), $pk_tourop));
        foreach ($pk_hdates as $pk_hin) {
            $pk_hout = date('Y-m-d', (int) strtotime($pk_hin . ' +' . $pk_hn . ' days'));
            echo "\n-- {$pk_hin} → {$pk_hout}: the city's hotel search (the storefront's own request)\n";
            [$pk_resp] = pk_call('getHotelPriceRequest', (string) $pk_payload_of->invoke($pk_api, [
                'country_code' => $pk_country,
                'city_code' => $pk_city,
                'tourop_code' => $pk_tourop,
                'check_in' => $pk_hin,
                'check_out' => $pk_hout,
                'currency' => 'EUR',
                'rooms' => [$pk_room],
            ]));
            $pk_row = ['city' => $pk_city, 'stay' => $pk_hin, 'hotel' => null, 'services' => [], 'why' => ''];
            if ($pk_resp === null) {
                $pk_supp[] = ['why' => 'the hotel search failed'] + $pk_row;
                continue;
            }
            $pk_hotels = pk_offers($pk_resp);
            echo count($pk_hotels), " hotel(s) answered\n";
            $pk_choice = pk_supplement_offer($pk_hotels, $pk_keys);
            if ($pk_choice === null) {
                echo "No offer of a store hotel on these dates (&hotel_check_in=YYYY-MM-DD asks others).\n";
                $pk_supp[] = ['why' => 'no offer of a store hotel'] + $pk_row;
                continue;
            }
            $pk_p = $pk_choice['hotel']['product'];
            $pk_o = $pk_choice['offer'];
            $pk_row['hotel'] = $pk_p;
            $pk_r0 = $pk_o['rooms'][0] ?? null;
            $pk_m0 = $pk_o['meals'][0] ?? null;
            echo sprintf(
                "\n%s %s (%s) · %s★ · %s %s · product #%s\n  offer: %s %s · %s → %s · %s %s · VariantId %s\n  room %s · meal %s\n",
                $pk_p['tourop'],
                $pk_p['code'],
                $pk_p['name'],
                $pk_p['category'],
                $pk_p['city_name'],
                $pk_p['city_code'],
                $pk_keys[$pk_p['tourop'] . '|' . $pk_p['code']]['product_id'],
                $pk_o['type'],
                $pk_o['availability'],
                $pk_o['check_in'],
                $pk_o['check_out'],
                $pk_o['price'],
                $pk_o['currency'],
                $pk_o['variant_id'],
                $pk_r0 !== null ? $pk_r0['gcode'] . ' "' . $pk_r0['name'] . '"' : '—',
                $pk_m0 !== null ? $pk_m0['name'] : '—',
            );
            echo $pk_o['services'] === [] ? "  in the offer's price: no service listed\n" : "  in the offer's price:\n";
            foreach ($pk_o['services'] as $pk_sv) {
                echo sprintf(
                    "    - [%s %s] %s · %s%s\n",
                    $pk_sv['type'],
                    $pk_sv['kind'],
                    $pk_sv['name'],
                    $pk_sv['price'] !== '' ? $pk_sv['price'] . ' ' . $pk_o['currency'] : '—',
                    $pk_sv['transport'] !== '' ? ' (' . $pk_sv['transport'] . ')' : '',
                );
            }
            $pk_in = $pk_o['check_in'] !== '' ? $pk_o['check_in'] : $pk_hin;
            $pk_out = $pk_o['check_out'] !== '' ? $pk_o['check_out'] : $pk_hout;
            $pk_where = '<CountryCode>' . $pk_builder::esc($pk_country) . '</CountryCode>'
                . '<CityCode>' . $pk_builder::esc($pk_city) . '</CityCode>'
                . '<TourOpCode>' . $pk_builder::esc($pk_p['tourop']) . '</TourOpCode>'
                . '<ProductCode>' . $pk_builder::esc($pk_p['code']) . '</ProductCode>';
            $pk_stay = '<PeriodOfStay><CheckIn>' . $pk_builder::esc($pk_in) . '</CheckIn><CheckOut>' . $pk_builder::esc($pk_out) . '</CheckOut></PeriodOfStay>';

            echo "\n-- the supplements of this offer\n";
            [$pk_types] = pk_call('getHotelServiceTypesRequest', '<getHotelServiceTypesRequest>' . $pk_where
                . '<VariantId>' . $pk_builder::esc($pk_o['variant_id']) . '</VariantId>'
                . '<Language>RO</Language>'
                . $pk_stay
                . '</getHotelServiceTypesRequest>');
            if ($pk_types === null) {
                $pk_supp[] = ['why' => 'the supplements call failed'] + $pk_row;
                continue;
            }
            $pk_services = pk_supplements($pk_types);
            $pk_row['services'] = $pk_services;
            echo count($pk_services), " supplement(s)\n";
            if ($pk_services === []) {
                echo "The answer holds no supplement. Its content:\n", pk_xml($pk_types, 2000), "\n";
            }
            foreach ($pk_services as $pk_sv) {
                echo sprintf(
                    "  - [%s %s] %s · code %s · %s%s\n",
                    $pk_sv['type'],
                    $pk_sv['type_name'] !== '' ? $pk_sv['type_name'] : $pk_sv['kind'],
                    $pk_sv['name'],
                    $pk_sv['code'],
                    $pk_sv['has_price'] ? 'priced' : 'no price',
                    $pk_sv['charter_id'] !== '' ? ' · CharterId ' . $pk_sv['charter_id'] : '',
                );
            }
            if ($pk_raw && $pk_services !== []) {
                echo "\nRaw supplements answer:\n", pk_xml($pk_types, 6000), "\n";
            }

            // What a transport supplement costs for the persons asked (the first three).
            $pk_priced = 0;
            foreach ($pk_services as $pk_sv) {
                if ($pk_sv['type'] !== '7' || !$pk_sv['has_price'] || $pk_priced >= 3) {
                    continue;
                }
                $pk_priced++;
                echo "\n-- the price of \"{$pk_sv['name']}\"\n";
                [$pk_resp] = pk_call('getHotelServicePriceRequest', '<getHotelServicePriceRequest>' . $pk_where
                    . '<CurrencyCode>EUR</CurrencyCode>'
                    . '<VariantId>' . $pk_builder::esc($pk_o['variant_id']) . '</VariantId>'
                    . '<Language>RO</Language>'
                    . '<Services><Service>'
                    . '<ServiceType>7</ServiceType>'
                    . '<ServiceCode>' . $pk_builder::esc($pk_sv['code']) . '</ServiceCode>'
                    . $pk_stay
