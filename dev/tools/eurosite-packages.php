/**
 * @param string $key the parameter (?key=value, or key=value on the CLI)
 * @param string $default when it is not given
 *
 * @return string request/CLI parameter
 */
function pk_param(string $key, string $default = ''): string
{
    if (PHP_SAPI === 'cli') {
        foreach (array_slice((array) ($GLOBALS['argv'] ?? []), 1) as $arg) {
            if (str_starts_with((string) $arg, $key . '=')) {
                return trim(substr((string) $arg, strlen($key) + 1));
